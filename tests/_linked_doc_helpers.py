"""Shared fixtures for the sheet-linked-document tests.

The two checked-in PDFs under ``tests/fixtures/linked_doc/`` are generated by
``python -m tests._linked_doc_helpers`` from the constants below. Every guard's
expected number cites these constants (the raw source), never the module under
test.
"""
from __future__ import annotations

import os
import time
from pathlib import Path

import fitz

FIXTURE_DIR = Path(__file__).parent / "fixtures" / "linked_doc"
TWO_PAGE = FIXTURE_DIR / "two_page_17x11.pdf"
ONE_PAGE = FIXTURE_DIR / "one_page_17x11.pdf"

PAGE_W_PT = 1224.0                      # 17 in x 72 pt
PAGE_H_PT = 792.0                       # 11 in x 72 pt
MM_PER_PT = 25.4 / 72.0
PT_PER_MM = 72.0 / 25.4

ALPHA_ORIGIN_PT = (72.0, 100.0)         # insert_text origin of FIXTURE-<tag>-P<n>
ALPHA_FONTSIZE = 12
OVERRUN_TEXT = "FIXTURE-OVERRUN"
OVERRUN_ORIGIN_PT = (1100.0, 400.0)     # 2x on ANSI D: inside the title-block strip
OVERRUN_FONTSIZE = 8
FRAME_RECT_PT = (1170.0, 300.0, 1200.0, 320.0)   # stroked; x1 = content right edge
MARK_RECT_PT = (200.0, 200.0, 240.0, 240.0)      # filled black square (pixel probe)


def fixture_text(tag: str, page: int) -> str:
    """The per-page fixture string, e.g. ``FIXTURE-ALPHA-P1``."""
    return f"FIXTURE-{tag}-P{page}"


def _build_doc(n_pages: int, tag: str) -> "fitz.Document":
    doc = fitz.open()
    for n in range(1, n_pages + 1):
        page = doc.new_page(width=PAGE_W_PT, height=PAGE_H_PT)
        page.insert_text(ALPHA_ORIGIN_PT, fixture_text(tag, n),
                         fontsize=ALPHA_FONTSIZE)
        page.insert_text(OVERRUN_ORIGIN_PT, OVERRUN_TEXT,
                         fontsize=OVERRUN_FONTSIZE)
        page.draw_rect(fitz.Rect(*FRAME_RECT_PT), color=(0, 0, 0), width=1)
        page.draw_rect(fitz.Rect(*MARK_RECT_PT), color=(0, 0, 0),
                       fill=(0, 0, 0), width=0)
    return doc


def build_fixture_pdf(path, n_pages: int, tag: str = "ALPHA") -> Path:
    """Write an *n_pages* 17x11 fixture PDF to *path* and return the path."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = _build_doc(n_pages, tag)
    try:
        doc.save(str(path))
    finally:
        doc.close()
    return path


def pdf_bytes(n_pages: int, tag: str = "ALPHA") -> bytes:
    """The fixture PDF as bytes (the stand-in for a Word conversion result)."""
    doc = _build_doc(n_pages, tag)
    try:
        return doc.tobytes()
    finally:
        doc.close()


def rewrite_by_rename(path, n_pages: int, tag: str) -> None:
    """Replace *path* the way Word and OneDrive save: temp file, then rename."""
    path = Path(path)
    tmp = path.with_name("~" + path.name + ".tmp")
    build_fixture_pdf(tmp, n_pages, tag)
    os.replace(tmp, path)


def snapshot_text(data) -> str:
    """All text of a ``LinkedDocData`` snapshot (decoded with fitz directly)."""
    import base64
    doc = fitz.open(stream=base64.b64decode(data.snapshot_pdf), filetype="pdf")
    try:
        return "".join(page.get_text() for page in doc)
    finally:
        doc.close()


def word_bbox(page, text: str):
    """(x0, y0, x1, y1) of the first word equal to *text* on a fitz page."""
    for w in page.get_text("words"):
        if w[4] == text:
            return tuple(w[:4])
    raise AssertionError(f"{text!r} not on the page")


def make_link(path, page: int = 1, scale_mode: str = "fit",
              scale_custom: float = 1.0):
    """A ``LinkedDocData`` for *path* built through ``linked_document.new_link``."""
    from firepro3d.linked_document import new_link
    path = os.path.abspath(str(path))
    st = os.stat(path)
    with open(path, "rb") as fh:
        data = fh.read()
    return new_link(path, data, page, st.st_mtime, st.st_size,
                    scale_mode=scale_mode, scale_custom=scale_custom)


def pump_until(predicate, timeout_s: float) -> bool:
    """Process Qt events until *predicate()* is true or *timeout_s* passes."""
    from PyQt6.QtCore import QCoreApplication, QEventLoop
    end = time.monotonic() + timeout_s
    while time.monotonic() < end:
        QCoreApplication.processEvents(
            QEventLoop.ProcessEventsFlag.AllEvents, 50)
        if predicate():
            return True
        time.sleep(0.01)
    return bool(predicate())


def render_scene(scene, w_mm: float, h_mm: float, px_per_mm: float):
    """Render the paper rect of *scene* into a white QImage at *px_per_mm*."""
    from PyQt6.QtCore import QRectF, Qt
    from PyQt6.QtGui import QImage, QPainter
    img = QImage(int(round(w_mm * px_per_mm)), int(round(h_mm * px_per_mm)),
                 QImage.Format.Format_RGB32)
    img.fill(Qt.GlobalColor.white)
    p = QPainter(img)
    scene.render(p, QRectF(0, 0, img.width(), img.height()),
                 QRectF(0, 0, w_mm, h_mm))
    p.end()
    return img


def dark_at(img, x_mm: float, y_mm: float, px_per_mm: float) -> bool:
    """True when the pixel at paper point (x_mm, y_mm) is dark (red < 80)."""
    from PyQt6.QtGui import QColor
    c = QColor(img.pixel(int(x_mm * px_per_mm), int(y_mm * px_per_mm)))
    return c.red() < 80


